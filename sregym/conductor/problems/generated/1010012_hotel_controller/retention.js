// Catalog import retention reconciler. Policy is refreshed on every pass.
var policy = JSON.parse(cat('/etc/catalog/policy.json'));
var catalog = db.getSiblingDB(policy.database);
// Resolve a collection policy qualified by an import namespace.
var collection = policy.collection.split(".").pop();
var live = catalog.getCollection(collection);
var versions = catalog.getCollection(policy.historyCollection);
var selector = {id: {$in: policy.catalogIds}};
var candidates = live.find(selector).toArray();
candidates.forEach(function(record) {
    // Keep the first full revision so an operator can reverse an import cleanup.
    if (!versions.findOne({catalogId: record.id})) {
        var original = Object.extend({}, record);
        delete original._retention;
        versions.insert({catalogId: record.id, sourceCollection: collection, archivedAt: new Date(), payload: original});
    }
    var importedAt = record.importedAt || new Date(policy.legacyImportEpoch);
    var deadline = new Date(new Date(importedAt).getTime() + policy.retentionSeconds * 1000);
    live.update({_id: record._id}, {$set: {'_retention.expiresAt': deadline}});
});
live.createIndex({'_retention.expiresAt': 1}, {name: 'catalog_retention', expireAfterSeconds: 0});
// Run the same expiry predicate during reconciliation as during MongoDB TTL passes.
var result = live.remove({'_retention.expiresAt': {$lte: new Date()}});
print('catalog retention completed candidates=' + candidates.length + ' removed=' + result.nRemoved);

// Invalidate retired catalog entries, including those regenerated by old importers.
versions.find({sourceCollection: collection}).forEach(function(v) {
    if (!live.findOne({id: v.catalogId})) print('expired_catalog_key=' + v.catalogId);
});
